export function calcContoProgressivo(conto: Partial<BilancioConto>): number {
  const sum =
    (Number(conto.lug_ott) || 0) +
    (Number(conto.novembre) || 0) +
    (Number(conto.dicembre) || 0) +
    (Number(conto.gennaio) || 0) +
    (Number(conto.febbraio) || 0) +
    (Number(conto.marzo) || 0) +
    (Number(conto.aprile) || 0) +
    (Number(conto.maggio) || 0) +
    (Number(conto.giugno) || 0);
  return Math.round(sum * 100) / 100;
}

